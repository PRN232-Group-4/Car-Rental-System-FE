export function useFleetVehicles() {
  return useQuery({
    queryKey: ["public-fleet", "available", 6],
    queryFn: async () => {
      try {
        const result = await getVehiclesPaginated({ status: "available", page: 1, pageSize: 6 });
        const available = (result?.items ?? []).filter((vehicle) => vehicle.isAvailable).slice(0, 6);
        return available.length > 0 ? available : FALLBACK_FLEET_VEHICLES;
      } catch {
        return FALLBACK_FLEET_VEHICLES;
      }
    },
    initialData: FALLBACK_FLEET_VEHICLES,
    staleTime: 30_000,
  });
}
